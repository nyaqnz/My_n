-- NOIR ROUGE private dream archive
-- Supabase SQL Editorで実行する前に、下記の YOUR_OWNER_EMAIL を管理者メールに置換してください。
-- Auth > Users で管理者ユーザーを作成してから実行してください。

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  page text not null check (page in ('majestic','hazbin','pokemon')),
  body text not null,
  image_path text,
  created_at timestamptz not null default now()
);

create table if not exists public.site_settings (
  key text primary key,
  value text not null
);

alter table public.posts enable row level security;
alter table public.site_settings enable row level security;

-- ログイン済みの招待ユーザーは閲覧できる
create policy "authenticated users can read posts"
on public.posts for select to authenticated using (true);

create policy "authenticated users can read site settings"
on public.site_settings for select to authenticated using (true);

-- 管理者メールアドレスのユーザーだけが投稿・編集・削除できる
create policy "owner can insert posts"
on public.posts for insert to authenticated
with check (lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL'));

create policy "owner can update posts"
on public.posts for update to authenticated
using (lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL'))
with check (lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL'));

create policy "owner can delete posts"
on public.posts for delete to authenticated
using (lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL'));

create policy "owner can insert site settings"
on public.site_settings for insert to authenticated
with check (lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL'));

create policy "owner can update site settings"
on public.site_settings for update to authenticated
using (lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL'))
with check (lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL'));

-- Private bucket: 画像URLはログイン後に期限付きURLとして発行
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('site-media', 'site-media', false, 10485760, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public=false, file_size_limit=10485760;

create policy "authenticated users can view site media"
on storage.objects for select to authenticated
using (bucket_id = 'site-media');

create policy "owner can upload site media"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'site-media'
  and lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL')
);

create policy "owner can update site media"
on storage.objects for update to authenticated
using (
  bucket_id = 'site-media'
  and lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL')
)
with check (
  bucket_id = 'site-media'
  and lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL')
);

create policy "owner can delete site media"
on storage.objects for delete to authenticated
using (
  bucket_id = 'site-media'
  and lower(coalesce(auth.jwt()->>'email','')) = lower('YOUR_OWNER_EMAIL')
);
